#!/usr/bin/env python3
"""Write src/picasso_site_releases.mjs from the repo's v* tags: the latest version, what is
unreleased on HEAD, a changelog per release grouped by commit type, and the Zenodo DOIs. Run by
`just build` and `just test` before Gleam compiles, so the page carries this data in its bundle and
its prerendered HTML and the browser fetches none of it. Generated, never committed, because a
release must not need a commit after its tag. A clone without tags (CI's shallow checkout) gets no
version and an empty changelog.

The concept DOI comes from CITATION.cff. Zenodo mints a version DOI some time after the tag, so the
version DOIs are asked from its API at build time; when Zenodo cannot be reached the build keeps
the concept DOI and shows no version DOI.

  python3 releases.py [out]      # default src/picasso_site_releases.mjs
  python3 releases.py --self-test
"""
import json
import pathlib
import re
import subprocess
import sys
import urllib.parse
import urllib.request

SITE = pathlib.Path(__file__).resolve().parent
REPO = "https://github.com/h0ffmann/picasso"
SEMVER = re.compile(r"^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
CITATION = SITE.parent / "CITATION.cff"
ZENODO = "https://zenodo.org/api/records"
GROUPS = [("feat", "Features"), ("fix", "Fixes"), ("docs", "Documentation")]
OTHER = "Other changes"


def git(*args):
    return subprocess.run(["git", "-C", str(SITE), *args], capture_output=True, text=True).stdout


def entry(subject):
    """`feat(site)!: x (#92)` -> (group title, {"subject": "site: x", "pr": 92, "breaking": True})."""
    pr = re.search(r" \(#(\d+)\)$", subject)
    text = subject[:pr.start()] if pr else subject
    m = re.match(r"^(\w+)(?:\(([^)]*)\))?(!)?: (.*)$", text)
    kind, scope, bang, text = (m.group(1), m.group(2), m.group(3), m.group(4)) if m else ("", None, None, text)
    title = dict(GROUPS).get(kind, OTHER)
    return title, {"subject": f"{scope}: {text}" if scope else text,
                   "pr": int(pr.group(1)) if pr else None, "breaking": bool(bang)}


def grouped(rev_range):
    out = git("log", "--first-parent", "--format=%an%x1f%s", rev_range)
    groups = {}
    for line in filter(None, out.split("\n")):
        author, subject = line.split("\x1f", 1)
        if author.endswith("[bot]"):
            continue
        title, e = entry(subject)
        groups.setdefault(title, []).append(e)
    order = [t for _, t in GROUPS] + [OTHER]
    return [{"title": t, "entries": groups[t]} for t in order if t in groups]


def concept_doi(cff):
    m = re.search(r"^doi:\s*['\"]?(10\.5281/zenodo\.\d+)", cff, re.MULTILINE)
    return m.group(1) if m else None


def version_dois(concept, fetch):
    """{"v0.1.1": "10.5281/zenodo.23311209", ...} from Zenodo's records of the concept DOI: the 25
    newest, the most its API gives an anonymous caller in one page."""
    query = urllib.parse.urlencode({"q": f"conceptrecid:{concept.rsplit('.', 1)[1]}",
                                    "all_versions": "true", "sort": "newest", "size": 25})
    hits = json.loads(fetch(f"{ZENODO}?{query}"))["hits"]["hits"]
    return {h["metadata"]["version"]: h["doi"] for h in hits
            if h.get("conceptdoi") == concept and h.get("metadata", {}).get("version") and h.get("doi")}


def fetch(url):
    with urllib.request.urlopen(url, timeout=20) as res:
        return res.read().decode()


def build():
    refs = git("for-each-ref", "--sort=-v:refname", "--format=%(refname:short) %(creatordate:short)",
               "refs/tags/v*")
    tags = [line.split() for line in refs.split("\n") if line and SEMVER.match(line.split()[0])]
    releases = []
    for i, (tag, date) in enumerate(tags):
        previous = tags[i + 1][0] if i + 1 < len(tags) else None
        releases.append({"tag": tag, "date": date, "previous": previous,
                         "groups": grouped(f"{previous}..{tag}" if previous else tag)})
    version = tags[0][0] if tags else None
    unreleased = grouped(f"{version}..HEAD") if version else []
    doi = concept_doi(CITATION.read_text()) if CITATION.exists() else None
    dois = {}
    if doi:
        try:
            dois = version_dois(doi, fetch)
        except (OSError, ValueError, KeyError) as e:
            print(f"releases.py: no version DOIs, Zenodo not reached ({e})", file=sys.stderr)
    for rel in releases:
        rel["doi"] = dois.get(rel["tag"])
    return {"repo": REPO, "version": version, "doi": doi, "unreleased": unreleased, "releases": releases}


def module(data):
    # The JSON as a string literal: Gleam decodes it with the same decoder as any other source.
    return ("// Generated by site/releases.py; never edit or commit.\n"
            f"export const releases = () => {json.dumps(json.dumps(data, ensure_ascii=False))};\n")


def self_test():
    assert entry("feat(site): port the site to Gleam and Lustre (#92)") == (
        "Features", {"subject": "site: port the site to Gleam and Lustre", "pr": 92, "breaking": False})
    assert entry("feat(lint)!: drop ruff") == ("Features", {"subject": "lint: drop ruff", "pr": None, "breaking": True})
    assert entry("docs: a logo (#83)")[0] == "Documentation"
    assert entry("chore: bump (#68)")[0] == OTHER
    assert entry("picasso: the site (#81)") == (OTHER, {"subject": "the site", "pr": 81, "breaking": False})
    assert entry("Merge pull request #5 from x")[0] == OTHER
    assert all(SEMVER.match(t) for t in ("v0.1.0", "v10.0.3")) and not any(
        SEMVER.match(t) for t in ("v0.1", "v01.0.0", "v1.0.0-rc1"))
    assert concept_doi("cff-version: 1.2.0\ndoi: 10.5281/zenodo.23311208\n") == "10.5281/zenodo.23311208"
    assert concept_doi("identifiers:\n  - value: 10.5281/zenodo.1\n") is None
    zenodo = {"hits": {"hits": [
        {"doi": "10.5281/zenodo.9", "conceptdoi": "10.5281/zenodo.8", "metadata": {"version": "v0.1.1"}},
        {"doi": "10.5281/zenodo.7", "conceptdoi": "10.5281/zenodo.6", "metadata": {"version": "v9.9.9"}}]}}
    asked = []
    dois = version_dois("10.5281/zenodo.8", lambda url: asked.append(url) or json.dumps(zenodo))
    assert dois == {"v0.1.1": "10.5281/zenodo.9"} and "conceptrecid%3A8" in asked[0]
    js = module({"doi": "10.5281/zenodo.8", "s": 'a "quote" </script>'})
    assert json.loads(json.loads(js.split(" => ", 1)[1].rstrip(";\n")))["s"] == 'a "quote" </script>'
    print("releases.py: self-test ok")


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        self_test()
    else:
        out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else SITE / "src" / "picasso_site_releases.mjs"
        data = build()
        out.write_text(module(data))
        print(f"{out.name}: version {data['version'] or 'none'}, {len(data['releases'])} releases,"
              f" DOI {data['doi'] or 'none'}")
